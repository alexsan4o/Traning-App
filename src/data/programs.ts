function toItem([id, sets, amount, restSec]: Row, index: number, programId: string): WorkoutExercise {
  const ex = getBuiltinExercise(id);
  if (!ex) throw new Error(`Программа ${programId}: неизвестное упражнение ${id}`);
  return {
    uid: `${programId}_${index}`,
    exerciseId: ex.id,
    name: ex.name,
    category: ex.category,
    kind: ex.kind,
    muscles: ex.muscles,
    perSide: ex.perSide,
    tips: ex.tips,
    sets,
    reps: ex.kind === 'reps' ? amount : undefined,
    durationSec: ex.kind === 'time' ? amount : undefined,
    restSec,
  };
}

const EPOCH = '2026-01-01T00:00:00.000Z';

export const BUILTIN_WORKOUTS: Workout[] = defs.map((d) => ({
  id: `builtin_${d.id}`,
  title: d.title,
  description: d.description,
  sport: d.sport,
  goal: d.goal,
  level: d.level,
  tips: d.tips,
  source: 'builtin',
  exercises: d.rows.map((row, i) => toItem(row, i, d.id)),
  createdAt: EPOCH,
  updatedAt: EPOCH,
}));
